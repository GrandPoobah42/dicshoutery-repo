// Combine base Oxford words with extended short & common English words
const ALL_ENTRIES: LexiconWord[] = [...BASE_OXFORD_LEXICON, ...EXTENDED_SHORT_WORDS];

// Deduplicate words with precedence for primary antonym entries
const DEDUPED_MAP = new Map<string, LexiconWord>();
for (const entry of ALL_ENTRIES) {
  const existing = DEDUPED_MAP.get(entry.word);
  if (!existing || (!existing.primaryAntonym && entry.primaryAntonym)) {
    DEDUPED_MAP.set(entry.word, entry);
  }
}

export const OXFORD_LEXICON: LexiconWord[] = Array.from(DEDUPED_MAP.values());

// High-speed lookup map
export const OXFORD_MAP = new Map<string, LexiconWord>(
  OXFORD_LEXICON.map(item => [item.word, item])
);

/**
 * Look up word in lexicon (case-insensitive)
 * Features exact match + smart English inflection handling (plurals, past, participles)
 */
export function findLexiconWord(word: string): LexiconWord | undefined {
  const normalized = word.trim().toUpperCase();
  if (!normalized || normalized.length < 2) return undefined;

  // 1. Direct exact dictionary match
  const exact = OXFORD_MAP.get(normalized);
  if (exact) return exact;

  // 2. Regular plural in -S (e.g. DAYS -> DAY, CATS -> CAT, BIRDS -> BIRD, TREES -> TREE)
  if (normalized.endsWith('S') && normalized.length >= 3) {
    const root = normalized.slice(0, -1);
    const baseEntry = OXFORD_MAP.get(root);
    if (baseEntry) {
      return {
        word: normalized,
        tier: baseEntry.tier,
        partOfSpeech: baseEntry.partOfSpeech.includes('noun') ? 'noun (pl.)' : baseEntry.partOfSpeech,
        definition: `Plural of ${root.toLowerCase()}: ${baseEntry.definition}`,
        antonyms: baseEntry.antonyms,
        primaryAntonym: baseEntry.primaryAntonym,
      };
    }
  }

  // 3. Regular plural in -ES (e.g. BOXES -> BOX, FOXES -> FOX, BUSES -> BUS)
  if (normalized.endsWith('ES') && normalized.length >= 4) {
    const root = normalized.slice(0, -2);
    const baseEntry = OXFORD_MAP.get(root);
    if (baseEntry) {
      return {
        word: normalized,
        tier: baseEntry.tier,
        partOfSpeech: 'noun (pl.)',
        definition: `Plural of ${root.toLowerCase()}: ${baseEntry.definition}`,
        antonyms: baseEntry.antonyms,
        primaryAntonym: baseEntry.primaryAntonym,
      };
    }
  }

  // 4. Regular plural in -IES (e.g. CITIES -> CITY, BABIES -> BABY)
  if (normalized.endsWith('IES') && normalized.length >= 5) {
    const root = normalized.slice(0, -3) + 'Y';
    const baseEntry = OXFORD_MAP.get(root);
    if (baseEntry) {
      return {
        word: normalized,
        tier: baseEntry.tier,
        partOfSpeech: 'noun (pl.)',
        definition: `Plural of ${root.toLowerCase()}: ${baseEntry.definition}`,
        antonyms: baseEntry.antonyms,
        primaryAntonym: baseEntry.primaryAntonym,
      };
    }
  }

  // 5. Regular past in -ED (e.g. WALKED -> WALK, PLAYED -> PLAY, BURNED -> BURN)
  if (normalized.endsWith('ED') && normalized.length >= 4) {
    const root = normalized.slice(0, -2);
    const baseEntry = OXFORD_MAP.get(root) || OXFORD_MAP.get(normalized.slice(0, -1));
    if (baseEntry && baseEntry.partOfSpeech.includes('verb')) {
      return {
        word: normalized,
        tier: baseEntry.tier,
        partOfSpeech: 'verb (past)',
        definition: `Past tense of ${baseEntry.word.toLowerCase()}: ${baseEntry.definition}`,
        antonyms: baseEntry.antonyms,
        primaryAntonym: baseEntry.primaryAntonym,
      };
    }
  }

  // 6. Present participle in -ING (e.g. WALKING -> WALK, TALKING -> TALK, PLAYING -> PLAY)
  if (normalized.endsWith('ING') && normalized.length >= 5) {
    const root = normalized.slice(0, -3);
    const baseEntry = OXFORD_MAP.get(root) || OXFORD_MAP.get(root + 'E');
    if (baseEntry && baseEntry.partOfSpeech.includes('verb')) {
      return {
        word: normalized,
        tier: baseEntry.tier,
        partOfSpeech: 'verb (pres. part.)',
        definition: `Present participle of ${baseEntry.word.toLowerCase()}: ${baseEntry.definition}`,
        antonyms: baseEntry.antonyms,
        primaryAntonym: baseEntry.primaryAntonym,
      };
    }
  }

  return undefined;
}

/**
 * Check if candidate word is an accepted antonym for a target word
 */
export function validateAntonym(targetWord: string, candidateAntonym: string): boolean {
  const entry = findLexiconWord(targetWord);
  if (!entry) return false;
  const candidate = candidateAntonym.trim().toUpperCase();
  return entry.antonyms.some(a => a.toUpperCase() === candidate);
}
